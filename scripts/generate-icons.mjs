import { readFile, writeFile } from "node:fs/promises";
import { pathToFileURL } from "node:url";

const output = new URL("../src/renderer/octicons.mjs", import.meta.url);
export const iconNames = [
  "agent", "bell", "check", "check-circle", "checklist", "chevron-left", "chevron-right",
  "circle-slash", "clock", "comment-discussion", "copilot", "dash",
  "discussion-closed", "discussion-duplicate", "discussion-outdated", "gear", "git-commit",
  "git-merge", "git-merge-queue", "git-pull-request", "git-pull-request-closed",
  "git-pull-request-draft", "inbox", "issue-closed", "issue-opened", "mail", "question", "read",
  "report", "shield-lock", "skip", "sync", "tag", "triangle-right", "workflow", "x",
];

export function renderIcons({ icons, version, license }) {
  const selected = Object.fromEntries(iconNames.map(name => {
    const icon = icons[name]?.heights[24];
    if (!icon || !Number.isInteger(icon.width) || icon.width <= 0 || !icon.ast?.children.length) {
      throw new Error(`Octicon ${name} is missing a supported 24px variant.`);
    }
    const paths = icon.ast.children.map(node => {
      if (node.name !== "path" || node.children.length ||
          Object.keys(node.attributes).length !== 1 || typeof node.attributes.d !== "string" || !node.attributes.d) {
        throw new Error(`Octicon ${name} has unsupported SVG markup; review it before updating the generator.`);
      }
      return node.attributes.d;
    });
    return [name, { width: icon.width, paths }];
  }));
  return `// Generated by npm run icons:generate from @primer/octicons@${version}. Do not edit.
/*!
${license.trim().split(/\r?\n/).map(line => ` *${line ? ` ${line}` : ""}`).join("\n")}
 */
export const octicons = ${JSON.stringify(selected, null, 2)};
`;
}

async function loadOcticons() {
  const root = new URL(".", import.meta.resolve("@primer/octicons/package.json"));
  const [icons, metadata, manifest, license] = await Promise.all([
    import("@primer/octicons"),
    readFile(new URL("package.json", root), "utf8").then(JSON.parse),
    readFile(new URL("../package.json", import.meta.url), "utf8").then(JSON.parse),
    readFile(new URL("LICENSE", root), "utf8"),
  ]);
  if (metadata.version !== manifest.devDependencies["@primer/octicons"]) {
    throw new Error("Installed Octicons do not match package.json. Run npm ci --ignore-scripts --engine-strict.");
  }
  return { icons: icons.default, version: metadata.version, license };
}

export async function generateIcons({ check = false, load = loadOcticons, read = readFile, write = writeFile } = {}) {
  const content = renderIcons(await load());
  if (check) {
    if ((await read(output, "utf8")).replaceAll("\r\n", "\n") !== content) {
      throw new Error("Generated Octicons are stale. Run npm run icons:generate and commit src/renderer/octicons.mjs.");
    }
  } else {
    await write(output, content);
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  try {
    const args = process.argv.slice(2);
    if (args.length > 1 || args.length === 1 && args[0] !== "--check") {
      throw new Error("Usage: node scripts/generate-icons.mjs [--check]");
    }
    await generateIcons({ check: args[0] === "--check" });
    process.stdout.write(args.length ? "Generated Octicons are current.\n" : "Generated selected Octicons.\n");
  } catch (error) {
    process.stderr.write(`Icon generation stopped: ${error.message}\n`);
    process.exitCode = 1;
  }
}
